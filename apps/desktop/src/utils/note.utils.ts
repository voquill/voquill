import type {
  NoteCloudSync,
  NoteSegment,
  NoteSource,
  NoteStorage,
} from "@voquill/types";
import type { AppState } from "../state/app.state";
import { getIntl } from "../i18n";
import { getIsVoquillCloudUser } from "./member.utils";
import {
  getEffectivePostProcessingMode,
  getEffectiveTranscriptionMode,
  getGenerativePrefs,
} from "./user.utils";

/** The signed-in Voquill cloud account whose cloud notes this device shows. */
export const getCloudNotesUserId = (state: AppState): string | null =>
  state.auth && !state.isEnterprise ? state.auth.uid : null;

/**
 * The storage a new note gets; it never changes afterwards. Cloud needs a
 * signed-in Voquill cloud member with both transcription and post-processing
 * set to Voquill cloud; anything else (API keys, local Whisper, enterprise,
 * signed out) is local.
 */
export const selectNoteStorage = (state: AppState): NoteStorage =>
  getCloudNotesUserId(state) &&
  getIsVoquillCloudUser(state) &&
  getEffectiveTranscriptionMode(state) === "cloud" &&
  getEffectivePostProcessingMode(state) === "cloud"
    ? "cloud"
    : "local";

export const createNoteCloudSync = (
  storage: NoteStorage,
  ownerUserId: string | null,
): NoteCloudSync | null =>
  storage === "cloud" && ownerUserId
    ? {
        ownerUserId,
        onServer: false,
        unsyncedFields: [],
        processRequestedAt: null,
        serverUpdatedAt: null,
        fetchedUpdatedAt: null,
      }
    : null;

/** Context for Voquill cloud and hosted API models (all have at least this). */
const HOSTED_MODEL_CONTEXT_TOKENS = 32_768;
/** Self-hosted servers (e.g. Ollama's default 2-4k) often run small windows. */
const SELF_HOSTED_MODEL_CONTEXT_TOKENS = 4_096;

/** The context window local note generation plans its requests for. */
export const getNoteGenerationContextTokens = (state: AppState): number => {
  const prefs = getGenerativePrefs(state);
  return prefs.mode === "api" &&
    (prefs.provider === "ollama" || prefs.provider === "openai-compatible")
    ? SELF_HOSTED_MODEL_CONTEXT_TOKENS
    : HOSTED_MODEL_CONTEXT_TOKENS;
};

/** AI notes, titles and Ask need the user's post-processing model. */
export const getNoteGenerationAvailable = (state: AppState): boolean =>
  state.enterpriseConfig?.allowPostProcessing !== false &&
  getGenerativePrefs(state).mode !== "none";

/** Cloud notes are generated by the server; local ones need the user's model. */
export const getNoteGenerationAvailableFor = (
  state: AppState,
  noteId: string,
): boolean =>
  state.noteById[noteId]?.storage === "cloud" ||
  getNoteGenerationAvailable(state);

/**
 * A meeting is being captured right now. Dictation's chimes and volume
 * dimming stay off meanwhile, so they are not recorded into the meeting.
 */
export const getIsMeetingCapturing = (state: AppState): boolean =>
  state.notes.capture !== null;

/** Recorded audio so far, including the segment being captured now. */
export const getNoteElapsedMs = (state: AppState, noteId: string): number => {
  const note = state.noteById[noteId];
  const capture = state.notes.capture;
  const live =
    capture?.noteId === noteId
      ? capture.durationMs - capture.initialDurationMs
      : 0;
  return (note?.durationMs ?? 0) + live;
};

export const formatNoteDuration = (ms: number): string => {
  const totalSeconds = Math.max(0, Math.floor(ms / 1000));
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;
  const pad = (value: number) => value.toString().padStart(2, "0");
  return hours > 0
    ? `${hours}:${pad(minutes)}:${pad(seconds)}`
    : `${minutes}:${pad(seconds)}`;
};

export const getDefaultNoteTitle = (
  source: NoteSource,
  createdAt: string,
): string => {
  const intl = getIntl();
  const date = intl.formatDate(createdAt, {
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
  return source === "import"
    ? intl.formatMessage(
        { defaultMessage: "Imported transcript, {date}" },
        { date },
      )
    : intl.formatMessage({ defaultMessage: "Meeting, {date}" }, { date });
};

/** Cheap enough for store selectors, unlike building the transcript text. */
export const getNoteHasTranscript = (
  state: AppState,
  noteId: string,
): boolean =>
  (state.noteSegmentsByNoteId[noteId] ?? []).some((segment) =>
    Boolean(segment.transcript?.text.trim()),
  );

export type NoteAskAvailability =
  | "available"
  | "post-processing-disabled"
  | "no-transcript"
  | "offline"
  | "limit-reached";

const hasAskableContent = (state: AppState, noteId: string): boolean => {
  const note = state.noteById[noteId];
  return Boolean(
    note &&
    (getNoteHasTranscript(state, noteId) ||
      (note.generatedNotes && note.status !== "processing")),
  );
};

/**
 * Whether Ask can answer about a note (or, with null, about all notes), and
 * why not. Cloud answers need the connection and the daily cap; local ones
 * need the user's post-processing model.
 */
export const getNoteAskAvailability = (
  state: AppState,
  noteId: string | null,
  now = Date.now(),
): NoteAskAvailability => {
  const storage = noteId
    ? state.noteById[noteId]?.storage
    : selectNoteStorage(state);
  if (storage === "cloud") {
    if (!state.notes.online) {
      return "offline";
    }
    const resetsAt = state.notes.askLimitResetsAt;
    if (resetsAt && Date.parse(resetsAt) > now) {
      return "limit-reached";
    }
  } else if (!getNoteGenerationAvailable(state)) {
    return "post-processing-disabled";
  }
  if (noteId) {
    return hasAskableContent(state, noteId) ? "available" : "no-transcript";
  }
  return Object.values(state.noteById).some(
    (note) => note.status === "ready" || note.generatedNotes,
  )
    ? "available"
    : "no-transcript";
};

/** Offsets each segment's utterances by the audio recorded before it. */
export const getNoteSegmentOffsetsMs = (
  segments: NoteSegment[],
): Map<string, number> => {
  const offsets = new Map<string, number>();
  let offset = 0;
  for (const segment of segments) {
    offsets.set(segment.id, offset);
    offset += segment.durationMs;
  }
  return offsets;
};
